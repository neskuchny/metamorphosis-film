#!/usr/bin/env node
/* Developer tool, not needed to make films. Regenerates player/map-data.js: land outlines (no borders) pre-projected with the
   Natural Earth projection, so the film player needs no map library and no network.
   Data: Natural Earth 1:110m land, public domain (no permission or credit needed), taken from the world-atlas package.
   Run from a folder where `npm i world-atlas topojson-client d3-geo` has been done:
     node build-map.mjs <path-to-repo>/player/map-data.js */
import fs from 'node:fs';
import { feature } from 'topojson-client';
import { geoPath, geoNaturalEarth1 } from 'd3-geo';

const out = process.argv[2] || 'map-data.js';
const S = 200;                                   // projection scale; film.js uses the same formula and the same S
const topo = JSON.parse(fs.readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const geoms = land.type === 'FeatureCollection' ? land.features.map((f) => f.geometry) : [land.geometry || land];
const polys = geoms.flatMap((g) => (g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates]))
  .filter((p) => Math.max(...p[0].map((c) => c[1])) > -58);   // drop Antarctica
const proj = geoNaturalEarth1().scale(S).translate([0, 0]).precision(0.1);
const d = geoPath(proj).digits(1)({ type: 'MultiPolygon', coordinates: polys });
const b = geoPath(proj).bounds({ type: 'MultiPolygon', coordinates: polys });
fs.writeFileSync(out, `/* Natural Earth 1:110m land, public domain. Generated by scripts/dev/build-map.mjs, do not edit.\n   Natural Earth projection (Savric et al.), scale ${S}, y down, origin at lon 0 / lat 0. */\nwindow.MAP_DATA = ${JSON.stringify({ S, bounds: b.map((p) => p.map((v) => +v.toFixed(1))), land: d })};\n`);
console.log('wrote', out, (fs.statSync(out).size / 1024).toFixed(0) + ' KB', 'polygons', polys.length);
